def _text(value):
    value = (value or "").strip() if isinstance(value, str) else value
    if value in (None, ""):
        return '<span class="blank">&nbsp;</span>'
    return escape(str(value)).replace("\n", "<br>")


def _when(value):
    if not value:
        return '<span class="blank">&nbsp;</span>'
    return escape(facility_time.local_datetime(value).strftime("%d %b %Y, %H:%M"))


def _rows(pairs):
    return "<table>" + "".join(f"<tr><th>{escape(k)}</th><td>{v}</td></tr>" for k, v in pairs) + "</table>"


def _yes_no(value):
    return "Yes" if value else "No"


def _track(incident, code):
    return next((t for t in incident.notifications.all() if t.track == code), None)


def _categories(incident):
    labels = dict(SECOND_SCHEDULE_CATEGORIES)
    chosen = [labels[c] for c in incident.schedule_categories if c in labels]
    return "<br>".join(escape(c) for c in chosen) if chosen else "None identified"


def _chronology(incident):
    events = list(incident.events.all())
    if not events:
        return "<p>No steps recorded.</p>"
    return (
        "<ol>"
        + "".join(
            f"<li>{_when(e.occurred_at)} — {_text(e.note)}"
            f"{' (' + escape(e.recorded_by.get_full_name()) + ')' if e.recorded_by else ''}</li>"
            for e in events
        )
        + "</ol>"
    )


def _profile(incident):
    return TenantComplianceProfile.all_objects.filter(organization=incident.organization).first()


def _page(organization, title, statute, body, user):
    generated = facility_time.local_now().strftime("%d %b %Y, %H:%M")
    by = escape(user.get_full_name()) if user else ""
    return (
        "<!doctype html><html><head><meta charset='utf-8'>"
        f"<title>{escape(title)}</title><style>{CSS}</style></head><body><div class='page'>"
        f"<div class='letterhead'><div class='org'>{escape(organization.name)}</div></div>"
        f"<div class='statute'>{escape(statute)}</div><h1>{escape(title)}</h1>{body}"
        f"<div class='footer'>Generated by CITRAMAC on {generated} by {by}. "
        "Built from the incident record — check every entry before submitting.</div>"
        "</div></body></html>"
    )


def _late_line(track):
    if track is None or not track.notified_at or not track.has_deadline:
        return '<span class="blank">&nbsp;</span>'
    if track.notified_at <= track.due_at:
        return "No — within the deadline"
    return f"Yes. Reasons for the delay: {_text(track.late_reason)}"


def _odpc(incident, user):
    track = _track(incident, "ODPC")
    subjects = _track(incident, "DATA_SUBJECTS")
    if incident.subjects_exemption:
        subjects_line = (
            f"Not notified — {escape(incident.get_subjects_exemption_display())}.<br>"
            f"Grounds: {_text(incident.subjects_exemption_grounds)}"
        )
    elif subjects and subjects.notified_at:
        subjects_line = f"Notified {_when(subjects.notified_at)} by {_text(subjects.method)}"
    else:
        subjects_line = "Not yet notified"
    body = (
        "<h2>Reporting organisation</h2>"
        + _rows(
            [
                ("Organisation", _text(incident.organization.name)),
                ("Reported as", _text(incident.get_reported_role_display())),
                ("Authorised representative — reg. 38(1)(i)", _text(_representative(incident))),
                ("Incident reference", _text(incident.reference)),
            ]
        )
        + "<h2>The breach</h2>"
        + _rows(
            [
                ("Date the breach occurred (best estimate)", _when(incident.occurred_at)),
                ("Date and circumstances of becoming aware — reg. 38(1)(a)", _when(incident.became_aware_at)),
                ("Description", _text(incident.description)),
                ("Primary cause", _text(incident.get_cause_display())),
                ("How it occurred — reg. 38(1)(c)", _text(incident.how_it_occurred)),
                ("Number of data subjects affected — reg. 38(1)(d)", _text(incident.subjects_affected)),
                (
                    "Personal data or classes of data affected — reg. 38(1)(e)",
                    _text(incident.data_categories)
                    + ("<br>Health information involved" if incident.involves_health_data else ""),
                ),
                ("Second Schedule classes involved (reg. 37)", _categories(incident)),
                ("Potential harm to the data subjects — reg. 38(1)(f)", _text(incident.likely_harm)),
                ("Other entities affected", _text(incident.other_entities_affected)),
                ("Police or other regulators notified", _text(incident.other_reports)),
            ]
        )
        + "<h2>Assessment that the breach is notifiable — reg. 38(1)(b)</h2>"
        + _rows(
            [
                ("Names or identification numbers involved", _yes_no(incident.identifies_subjects)),
                ("Account credentials involved (reg. 37(1)(b))", _yes_no(incident.credentials_exposed)),
                ("Only publicly available data (reg. 37(3))", _yes_no(incident.publicly_available_only)),
                ("Notifiable under reg. 37", _yes_no(incident.is_notifiable)),
                ("Risk assessment", _text(incident.get_risk_level_display())),
                ("Reasoning", _text(incident.notifiability_reasoning)),
            ]
        )
        + "<h3>Chronological account of the steps taken</h3>"
        + _chronology(incident)
        + "<h2>Response</h2>"
        + _rows(
            [
                ("Actions to mitigate the harm — reg. 38(1)(g)(i)", _text(incident.containment_actions)),
                ("Actions to remedy the cause / prevent recurrence — reg. 38(1)(g)(ii)", _text(incident.remedy_actions)),
                ("Notification to data subjects — reg. 38(1)(h)", subjects_line),
                ("How data subjects can mitigate the harm", _text(incident.subject_guidance)),
                ("Reported after 72 hours of becoming aware? — DPA s.43(2)", _late_line(track)),
            ]
        )
        + "<div class='note'>Submit through the ODPC online breach form "
        "(https://www.odpc.go.ke/report-a-data-breach/). Attach copies of any data-subject "
        "communication and of reports made to the police or another regulator.</div>"
    )
    return _page(
        incident.organization,
        "Notification of a personal data breach to the Data Commissioner",
        "Data Protection Act, 2019, s.43 · Data Protection (General) Regulations, 2021, reg. 38",
        body,
        user,
    )


def _representative(incident):
    profile = _profile(incident)
    parts = []
    if incident.reported_by:
        parts.append(incident.reported_by.get_full_name())
        if incident.reported_by.email:
            parts.append(incident.reported_by.email)
    if profile and profile.dpo_name:
        parts.append(f"Data Protection Officer: {profile.dpo_name} {profile.dpo_email} {profile.dpo_phone}")
    return " · ".join(p.strip() for p in parts if p.strip())


def _hmis1(incident, user):
    profile = _profile(incident)
    track = _track(incident, "DHA")
    reporter = incident.reported_by
    body = (
        "<h2>Data controller</h2>"
        + _rows(
            [
                ("Full name", _text(reporter.get_full_name() if reporter else "")),
                ("ID / passport number", _text("")),
                ("Sex", _text("")),
                ("Organisation", _text(incident.organization.name)),
                ("Position", _text("")),
                ("Email", _text(reporter.email if reporter else "")),
                ("County", _text(getattr(incident.organization, "county", ""))),
                ("Telephone", _text(reporter.phone if reporter else "")),
            ]
        )
        + "<h2>Data Protection Officer</h2>"
        + _rows(
            [
                ("Name", _text(profile.dpo_name if profile else "")),
                ("ID / passport number", _text("")),
                ("Sex", _text("")),
                ("Email", _text(profile.dpo_email if profile else "")),
            ]
        )
        + "<h2>Digital health solution</h2>"
        + _rows(
            [
                ("Solution name", "CITRAMAC"),
                (
                    "DHS Certification of Compliance No.",
                    _text(profile.dhs_certification_number if profile else ""),
                ),
                ("Description", "Electronic health record for mental health and addiction treatment"),
            ]
        )
        + "<h2>Breach</h2>"
        + _rows(
            [
                ("Date the breach occurred", _when(incident.occurred_at)),
                ("Date the breach was discovered", _when(incident.became_aware_at)),
                ("Was the breach reported within 48 hrs of discovery? If not, why", _late_line(track)),
                ("Cause", _text(incident.get_cause_display())),
                ("How the breach occurred", _text(incident.how_it_occurred)),
                ("Description", _text(incident.description)),
                ("Type of information", _text(incident.data_categories)),
                ("Categories (patient / human resource / administrative / de-identified / aggregate)", _text("")),
                ("Exact number of data subjects affected", _text(incident.subjects_affected)),
                ("Effect of the breach", _text(incident.likely_harm)),
                ("Remedial actions", _text(incident.containment_actions)),
                ("Prevention of recurrence", _text(incident.remedy_actions)),
                ("Steps recommended to affected individuals", _text(incident.subject_guidance)),
                ("Other entities affected", _text(incident.other_entities_affected)),
            ]
        )
        + "<h2>Declaration</h2><p>I declare that the information given is true and authorise the "
        "DHA to validate and verify it.</p>"
        "<p>Signature <span class='blank'>&nbsp;</span> &nbsp; Date <span class='blank'>&nbsp;</span></p>"
        "<div class='note'>VERIFY before submitting: DHA has not published a submission channel "
        "for Form HMIS 1 — confirm with the Digital Health Agency how it is to be lodged.</div>"
    )
    return _page(
        incident.organization,
        "Form HMIS 1 — Notification of Breach",
        "Digital Health (Health Information Management Procedures) Regulations, 2025, reg. 11(2)(a)",
        body,
        user,
    )


def _dha_followup(incident, user):
    dha = _track(incident, "DHA")
    body = _rows(
        [
            ("Incident reference", _text(incident.reference)),
            ("Form HMIS 1 notified on", _when(dha.notified_at if dha else None)),
            ("HMIS 1 reference", _text(dha.reference if dha else "")),
            ("(i) Corrective measures taken", _text(incident.remedy_actions)),
            ("(ii) Mitigation action adopted", _text(incident.containment_actions)),
            ("(iii) Timelines for the rectification of the breach", _text(incident.rectification_timeline)),
        ]
    ) + "<h2>Steps taken so far</h2>" + _chronology(incident)
    return _page(
        incident.organization,
        "Breach follow-up to the Chief Executive Officer, Digital Health Agency",
        "Digital Health (Health Information Management Procedures) Regulations, 2025, reg. 11(2)(b)",
        body,
        user,
    )


def _subject_letter(incident, user):
    profile = _profile(incident)
    contact = (
        f"{profile.dpo_name}, {profile.dpo_email} {profile.dpo_phone}".strip(", ")
        if profile and profile.dpo_name
        else ""
    )
    body = (
        "<p>Date: <span class='blank'>&nbsp;</span></p>"
        "<p>Dear <span class='blank'>&nbsp;</span>,</p>"
        f"<p>We are writing to tell you about an incident affecting personal data that "
        f"{escape(incident.organization.name)} holds about you.</p>"
        "<h2>What happened</h2>"
        f"<p>{_text(incident.description)}</p>"
        f"<p>Information involved: {_text(incident.data_categories)}</p>"
        "<h2>What we have done</h2>"
        f"<p>{_text(incident.containment_actions)}</p>"
        f"<p>{_text(incident.remedy_actions)}</p>"
        "<h2>What you can do</h2>"
        f"<p>{_text(incident.subject_guidance)}</p>"
        + (
            f"<h2>Who obtained the information</h2><p>{_text(incident.unauthorised_party)}</p>"
            if incident.unauthorised_party.strip()
            else ""
        )
        + "<h2>Contact</h2>"
        f"<p>If you have questions, contact our Data Protection Officer: {_text(contact)}</p>"
        "<p>Yours sincerely,</p><p><span class='blank'>&nbsp;</span></p>"
        "<div class='note'>Content required by DPA s.43(5): (a) nature of the breach; (b) measures "
        "taken or intended; (c) recommended measures for the data subject; (d) where applicable, "
        "the identity of the unauthorised person; (e) DPO or other contact point. The facility's "
        "own wording from counsel takes precedence over this draft.</div>"
    )
    return _page(
        incident.organization,
        "Notice of a personal data breach",
        "Data Protection Act, 2019, s.43(1)(b) and (5)",
        body,
        user,
    )


_RENDERERS = {
    "odpc": _odpc,
    "dha_hmis1": _hmis1,
    "dha_followup": _dha_followup,
    "subject_letter": _subject_letter,
}


def render(kind, incident, user):
    return _RENDERERS[kind](incident, user)


def render_register(organization, incidents, user):
    rows = []
    for incident in incidents:
        tracks = "<br>".join(
            f"{escape(t.get_track_display())}: "
            + (escape(facility_time.local_datetime(t.notified_at).strftime("%d %b %Y")) if t.notified_at else "pending")
            for t in incident.notifications.all()
            if t.required
        )
        rows.append(
            "<tr>"
            f"<td>{escape(incident.reference)}</td>"
            f"<td>{_when(incident.became_aware_at)}</td>"
            f"<td>{_text(incident.title)}<br>{_text(incident.description)}</td>"
            f"<td>{_text(incident.likely_harm)}</td>"
            f"<td>{_text(incident.containment_actions)}<br>{_text(incident.remedy_actions)}</td>"
            f"<td>{_yes_no(incident.is_notifiable)} / {escape(incident.get_risk_level_display())}</td>"
            f"<td>{tracks or '—'}</td>"
            f"<td>{escape(incident.get_status_display())}</td>"
            "</tr>"
        )
    body = (
        "<table class='register'><tr><th>Ref.</th><th>Aware</th><th>Facts</th><th>Effects</th>"
        "<th>Remedial action</th><th>Notifiable / risk</th><th>Notifications</th><th>Status</th></tr>"
        + ("".join(rows) or "<tr><td colspan='8'>No breaches recorded.</td></tr>")
        + "</table>"
    )
    return _page(
        organization,
        "Register of personal data breaches",
        "Data Protection Act, 2019, s.43(8) — facts, effects and remedial action of every breach",
        body,
        user,
    )

