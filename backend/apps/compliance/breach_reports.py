"""
Printable breach notices, built from the incident record so nothing is typed
twice. The content each must carry comes from the gazetted texts:

- odpc — notice to the Data Commissioner: Data Protection (General)
  Regulations 2021, reg. 38(1)(a)–(i) and 38(2); DPA 2019 s.43(2) for a late
  notice. The ODPC takes it through its online form
  (https://www.odpc.go.ke/report-a-data-breach/); this sheet is the record of
  what was submitted, laid out in the form's own order.
- dha_hmis1 — Form HMIS 1, "Notification of Breach", to the Digital Health
  Agency CEO: Digital Health (Health Information Management Procedures)
  Regulations 2025, reg. 11(2)(a) and the First Schedule.
- dha_followup — corrective measures, mitigation and rectification timeline
  within 72 hours of the HMIS 1 notice: reg. 11(2)(b).
- subject_letter — written communication to data subjects: DPA s.43(5)(a)–(e).
- the register (render_register) — facts, effects and remedial action for
  every breach, notifiable or not: DPA s.43(8).

No client is named in any of these: an incident is recorded at the level of
classes of data and numbers affected. Fields the record does not hold (the
signatory's ID number, a signature) print as blank lines to complete by hand.
"""

